import type { StepKind, Workflow } from "../types/workflow";
import { stepKindPresets } from "../data/stepKinds";
import type { ExportBundle, ExportFile } from "./bundleTypes";
import { fileSlug, planWorkflow, type PlannedStep, type WorkflowPlan } from "./plan";
import { buildStepPromptTemplate, gateVerdictJsonInstruction } from "./stepPrompt";
import { buildWorkflowJson } from "./workflowJson";

const DEFAULT_SANDBOX_MODE = "workspace-write";

type ManifestStep = {
  stepId: string;
  name: string;
  kind: StepKind;
  promptFile: string;
  artifactFile: string;
};

type ManifestUnit =
  | { kind: "step"; step: ManifestStep }
  | {
      kind: "loop";
      name: string;
      maxIterations: number;
      exitCondition: string;
      steps: ManifestStep[];
    };

const manifestStep = (planned: PlannedStep): ManifestStep => ({
  stepId: planned.step.id,
  name: planned.step.name,
  kind: planned.step.kind,
  promptFile: `prompts/${planned.slug}.md`,
  artifactFile: `${planned.slug}.md`,
});

const buildManifest = (workflow: Workflow, plan: WorkflowPlan) => ({
  workflowName: workflow.name,
  runner: {
    // Codex thread settings. model: null uses the Codex CLI default model.
    sandboxMode: DEFAULT_SANDBOX_MODE,
    model: null as string | null,
  },
  units: plan.units.map((unit): ManifestUnit => {
    if (unit.kind === "step") {
      return { kind: "step", step: manifestStep(unit.planned) };
    }
    return {
      kind: "loop",
      name: unit.block.name,
      maxIterations: Math.max(1, unit.block.maxIterations),
      exitCondition: unit.block.exitCondition,
      steps: unit.planned.map(manifestStep),
    };
  }),
});

const promptFile = (workflow: Workflow, planned: PlannedStep): ExportFile => {
  let content = buildStepPromptTemplate(workflow, planned.step);
  if (planned.step.kind === "gate") {
    content += `\n${gateVerdictJsonInstruction()}`;
  }
  return { path: `prompts/${planned.slug}.md`, content };
};

const agentsMd = (workflow: Workflow): ExportFile => ({
  path: "AGENTS.md",
  content: `# ${workflow.name}

${workflow.description || ""}

${workflow.context ? `## Shared Context\n\n${workflow.context}\n` : ""}
## How This Repository Is Worked On

This guidance accompanies the "${workflow.name}" workflow generated by Harness
Studio. Copy this file into the target repository root — the Codex agent reads
AGENTS.md from its working directory automatically.
`,
});

// The generated engine deliberately avoids template literals so this template
// needs no backtick/interpolation escaping.
const RUN_MJS = `#!/usr/bin/env node
// Workflow runner generated by Harness Studio — powered by the OpenAI Codex SDK.
//
// Each workflow step runs as a Codex agent thread that can read files, edit
// files, and run commands inside the target directory (within the configured
// sandbox mode). Step outputs are saved as artifacts and handed to later steps.
//
// Usage:
//   npm install
//   codex login                # or: export CODEX_API_KEY=...
//   node run.mjs [--dir <target-directory>] "<task description>"
//
// --dir defaults to the current working directory.

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { Codex } from "@openai/codex-sdk";

const here = path.dirname(fileURLToPath(import.meta.url));
const manifest = JSON.parse(fs.readFileSync(path.join(here, "manifest.json"), "utf8"));

const args = process.argv.slice(2);
let workingDirectory = process.cwd();
const taskParts = [];
for (let i = 0; i < args.length; i += 1) {
  if (args[i] === "--dir" && args[i + 1]) {
    workingDirectory = path.resolve(args[i + 1]);
    i += 1;
  } else {
    taskParts.push(args[i]);
  }
}
const task = taskParts.join(" ").trim();
if (!task) {
  console.error('Usage: node run.mjs [--dir <target-directory>] "<task description>"');
  process.exit(1);
}
if (!fs.existsSync(workingDirectory)) {
  console.error("Target directory does not exist: " + workingDirectory);
  process.exit(1);
}

const codex = new Codex();
const stamp = new Date().toISOString().replace(/[:.]/g, "-");
const runDir = path.join(here, "runs", stamp);
fs.mkdirSync(runDir, { recursive: true });

const MAX_ARTIFACT_CHARS = 60000;
const artifacts = []; // { stepId, name, content } — latest output per step
const summary = [];

const VERDICT_SCHEMA = {
  type: "object",
  properties: {
    pass: { type: "boolean" },
    reasons: { type: "array", items: { type: "string" } },
    fixInstructions: { type: "string" },
  },
  required: ["pass", "reasons", "fixInstructions"],
  additionalProperties: false,
};

function newThread() {
  const options = {
    workingDirectory: workingDirectory,
    sandboxMode: manifest.runner.sandboxMode,
    skipGitRepoCheck: true,
  };
  if (manifest.runner.model) {
    options.model = manifest.runner.model;
  }
  return codex.startThread(options);
}

function upstreamSection() {
  if (artifacts.length === 0) {
    return "This is the first step. There are no upstream outputs; work from the task and the files in your working directory.";
  }
  return artifacts
    .map(function (artifact) {
      const body =
        artifact.content.length > MAX_ARTIFACT_CHARS
          ? artifact.content.slice(0, MAX_ARTIFACT_CHARS) + "\\n...[truncated]"
          : artifact.content;
      return '### Output of step "' + artifact.name + '"\\n\\n' + body;
    })
    .join("\\n\\n");
}

function loadPrompt(step, loopFeedback) {
  const template = fs.readFileSync(path.join(here, step.promptFile), "utf8");
  let taskText = task;
  if (loopFeedback) {
    taskText +=
      "\\n\\n### Feedback from the previous attempt (address this first)\\n\\n" + loopFeedback;
  }
  // Function replacements keep "$&"-style sequences in the task text literal.
  return template
    .replace("{{TASK}}", function () {
      return taskText;
    })
    .replace("{{UPSTREAM}}", function () {
      return upstreamSection();
    });
}

function saveArtifact(step, content, iteration) {
  const suffix = iteration ? ".iter" + iteration : "";
  const fileName = step.artifactFile.replace(/\\.md$/, suffix + ".md");
  fs.writeFileSync(path.join(runDir, fileName), content);
  const entry = { stepId: step.stepId, name: step.name, content: content };
  const existing = artifacts.findIndex(function (artifact) {
    return artifact.stepId === step.stepId;
  });
  if (existing >= 0) {
    artifacts[existing] = entry;
  } else {
    artifacts.push(entry);
  }
}

function parseVerdict(raw) {
  try {
    return JSON.parse(raw);
  } catch {
    return {
      pass: false,
      reasons: ["The gate response could not be parsed as JSON."],
      fixInstructions: String(raw).slice(0, 2000),
    };
  }
}

// Runs one Codex turn, printing progress (commands, file changes, messages).
async function runCodex(prompt, options) {
  const structured = Boolean(options && options.structured);
  const thread = newThread();

  if (structured) {
    const turn = await thread.run(prompt, { outputSchema: VERDICT_SCHEMA });
    return turn.finalResponse;
  }

  const streamed = await thread.runStreamed(prompt);
  let finalResponse = "";
  for await (const event of streamed.events) {
    if (event.type === "item.completed") {
      const item = event.item;
      if (item.type === "agent_message") {
        finalResponse = item.text;
        console.log(item.text);
      } else if (item.type === "command_execution") {
        const exit = typeof item.exit_code === "number" ? " (exit " + item.exit_code + ")" : "";
        console.log("  $ " + item.command + exit);
      } else if (item.type === "file_change") {
        item.changes.forEach(function (change) {
          console.log("  ~ " + change.kind + " " + change.path);
        });
      } else if (item.type === "web_search") {
        console.log("  ? search: " + item.query);
      } else if (item.type === "error") {
        console.error("  ! " + item.message);
      }
    } else if (event.type === "turn.failed") {
      throw new Error(event.error && event.error.message ? event.error.message : "Turn failed.");
    } else if (event.type === "error") {
      throw new Error(event.message);
    }
  }
  return finalResponse;
}

async function runStep(step, options) {
  const iteration = options && options.iteration;
  const loopFeedback = options && options.loopFeedback;
  const header =
    "=== Step: " +
    step.name +
    " (" +
    step.kind +
    ")" +
    (iteration ? " [attempt " + iteration + "]" : "") +
    " ===";
  console.log("\\n" + header + "\\n");

  const prompt = loadPrompt(step, loopFeedback);

  if (step.kind === "gate") {
    const raw = await runCodex(prompt, { structured: true });
    const verdict = parseVerdict(raw);
    const report = [
      "# Gate: " + step.name,
      "",
      "Verdict: " + (verdict.pass ? "PASS" : "FAIL"),
      "",
      "Reasons:",
      (verdict.reasons || [])
        .map(function (reason) {
          return "- " + reason;
        })
        .join("\\n"),
      verdict.fixInstructions ? "\\nFix instructions:\\n" + verdict.fixInstructions : "",
    ].join("\\n");
    saveArtifact(step, report, iteration);
    console.log("Gate verdict: " + (verdict.pass ? "PASS" : "FAIL"));
    (verdict.reasons || []).forEach(function (reason) {
      console.log("- " + reason);
    });
    return { verdict: verdict };
  }

  const output = await runCodex(prompt);
  saveArtifact(step, output, iteration);
  return { output: output };
}

async function judgeLoopExit(unit) {
  const prompt = [
    'You are the exit-condition judge for the workflow loop "' + unit.name + '".',
    "Inspect the working directory and the outputs below, then decide whether the",
    "following exit condition is satisfied:",
    "",
    "Exit condition: " + unit.exitCondition,
    "",
    "Task:",
    task,
    "",
    "Outputs so far:",
    upstreamSection(),
  ].join("\\n");
  const raw = await runCodex(prompt, { structured: true });
  return parseVerdict(raw);
}

async function runLoop(unit) {
  let feedback = "";
  for (let iteration = 1; iteration <= unit.maxIterations; iteration += 1) {
    let gateVerdict = null;
    for (const step of unit.steps) {
      const result = await runStep(step, {
        iteration: iteration,
        loopFeedback: feedback || undefined,
      });
      if (result.verdict) {
        gateVerdict = result.verdict;
      }
    }
    const verdict =
      gateVerdict !== null
        ? gateVerdict
        : unit.exitCondition
          ? await judgeLoopExit(unit)
          : { pass: true, reasons: ["Loop has no gate step and no exit condition."], fixInstructions: "" };
    if (verdict.pass) {
      summary.push('Loop "' + unit.name + '" satisfied after ' + iteration + " attempt(s).");
      return;
    }
    feedback = (verdict.reasons || [])
      .concat(verdict.fixInstructions ? [verdict.fixInstructions] : [])
      .join("\\n");
    summary.push('Loop "' + unit.name + '" attempt ' + iteration + ": FAIL");
  }
  summary.push(
    'Loop "' +
      unit.name +
      '" UNRESOLVED after ' +
      unit.maxIterations +
      " attempts — continuing with remaining steps. Review the latest attempt artifacts.",
  );
}

console.log("Workflow: " + manifest.workflowName);
console.log("Target directory: " + workingDirectory);
console.log("Sandbox mode: " + manifest.runner.sandboxMode);

let stopped = false;
try {
  for (const unit of manifest.units) {
    if (stopped) {
      break;
    }
    if (unit.kind === "step") {
      const result = await runStep(unit.step);
      summary.push('Step "' + unit.step.name + '" completed.');
      if (unit.step.kind === "gate" && result.verdict && !result.verdict.pass) {
        summary.push('Gate "' + unit.step.name + '" FAILED outside a loop — run stopped.');
        console.error("\\nGate failed outside a loop. Stopping the run.");
        stopped = true;
      }
    } else {
      await runLoop(unit);
    }
  }
} catch (error) {
  summary.push("Run aborted: " + (error && error.message ? error.message : String(error)));
  console.error(error);
  process.exitCode = 1;
}

const summaryText = [
  "# Run Summary: " + manifest.workflowName,
  "",
  "Task:",
  "",
  task,
  "",
  "Target directory: " + workingDirectory,
  "",
  "Result log:",
  "",
  summary
    .map(function (line) {
      return "- " + line;
    })
    .join("\\n"),
  "",
  "Artifacts directory: " + runDir,
].join("\\n");
fs.writeFileSync(path.join(runDir, "run-summary.md"), summaryText);
console.log("\\n" + summaryText);
`;

const runnerReadme = (workflow: Workflow, steps: PlannedStep[]): ExportFile => ({
  path: "README.md",
  content: `# ${workflow.name} — Codex Workflow Runner

Harness Studio で作成したワークフローを、**OpenAI Codex SDK** で実際に実行する
ランナーです。各ステップは Codex のエージェントスレッドとして実行され、対象
ディレクトリの中でファイルの読み書き・コマンド実行ができます(サンドボックス内)。

## セットアップ

1. Node.js 18 以上を用意します。
2. 依存関係をインストールします。

   \`\`\`bash
   npm install
   \`\`\`

3. Codex の認証を済ませます(どちらか)。

   \`\`\`bash
   codex login                # ChatGPT アカウントでログイン
   export CODEX_API_KEY=...   # または API キー
   \`\`\`

## 実行

\`\`\`bash
# 対象リポジトリのディレクトリを指定して実行
node run.mjs --dir /path/to/your-repo "ここに実行したいタスクを書く"

# --dir を省略すると、いま居るディレクトリが対象になります
node run.mjs "ここに実行したいタスクを書く"
\`\`\`

- 各ステップの出力は \`runs/<タイムスタンプ>/\` に保存され、後続ステップに引き継がれます。
- 「チェック」ステップは構造化出力(JSON)で PASS / FAIL を判定します。
- ループは不合格の理由と修正指示を次の試行に引き継ぎ、最大回数に達したら
  UNRESOLVED として記録して残りのステップを続行します。
- 終了時に \`run-summary.md\` が生成されます。

## 安全について

- Codex は \`manifest.json\` の \`runner.sandboxMode\`(既定: \`${DEFAULT_SANDBOX_MODE}\`)の
  範囲でのみファイル変更・コマンド実行を行います。
- 対象ディレクトリは git 管理下で実行することを推奨します(差分の確認・巻き戻しのため)。

## カスタマイズ

| ファイル | 内容 |
| --- | --- |
| \`prompts/*.md\` | 各ステップのプロンプト(自由に編集可) |
| \`manifest.json\` | 実行計画(ステップ順・ループ・サンドボックス・モデル) |
| \`AGENTS.md\` | 対象リポジトリにコピーすると Codex が自動で読むガイダンス |
| \`workflow.json\` | ワークフロー設計の原本(Harness Studio に再インポート可) |

## ステップ一覧

${steps
  .map(
    (planned, index) =>
      `${index + 1}. ${planned.step.name}(${stepKindPresets[planned.step.kind].label})— \`prompts/${planned.slug}.md\``,
  )
  .join("\n")}

Generated by Harness Studio.
`,
});

const runnerPackageJson = (workflow: Workflow): ExportFile => ({
  path: "package.json",
  content: `${JSON.stringify(
    {
      name: `${fileSlug(workflow.name, "workflow")}-codex-runner`,
      private: true,
      version: "0.1.0",
      type: "module",
      scripts: {
        start: "node run.mjs",
      },
      dependencies: {
        "@openai/codex-sdk": "^0.139.0",
      },
    },
    null,
    2,
  )}\n`,
});

export function buildCodexRunnerPack(workflow: Workflow): ExportBundle {
  const plan = planWorkflow(workflow);
  const manifest = buildManifest(workflow, plan);

  const files: ExportFile[] = [
    runnerReadme(workflow, plan.steps),
    runnerPackageJson(workflow),
    { path: "run.mjs", content: RUN_MJS },
    { path: "manifest.json", content: `${JSON.stringify(manifest, null, 2)}\n` },
    agentsMd(workflow),
    ...plan.steps.map((planned) => promptFile(workflow, planned)),
    {
      path: "workflow.json",
      content: `${JSON.stringify(buildWorkflowJson(workflow), null, 2)}\n`,
    },
  ];

  return {
    name: `${fileSlug(workflow.name, "workflow")}-codex-runner`,
    description:
      "OpenAI Codex SDK でワークフローを自動実行するランナー(対象リポジトリのファイル編集・コマンド実行が可能)",
    files,
  };
}
